#include <iostream>
#include <string>
using namespace std;


int main()
{
    int a;
    int b;


    cout << "Enter Your First Number: " << endl;
    cin >> a;


    cout << "Enter Your Two Number: " << endl;
    cin >> b;


    cout << "a + b" << endl;
    cout << "a - b" << endl;
    cout << "a * b" << endl;
    cout << "a / b" << endl;


    cout << "sum = " << a + b << endl;
    cout << "subtraction = " << a - b << endl;
    cout << "multiplication = " << a * b << endl;
    cout << "Division = " << a / b << endl;


    return 0;
}
